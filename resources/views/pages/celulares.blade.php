            </div>
        </div>
    </div>
    <div class="div-section-text">
        <h3 class="h3_centrado">Con la normatividad aprobada, la autoridad educativa estatal expedirá lineamientos, protocolos, guías o manuales que contemplen:</h3>
        <div class="texto_section">
            <ul role="list" class="list">
                <li>
                    <p class="texto_general">Delimitar la utilización de teléfonos celulares y demás dispositivos electrónicos para fines expresamente académicos y pedagógicos, autorizados por el responsable del aula durante los horarios de clase.</p>
                </li>
                <li>
                    <p class="texto_general">Determinar tiempos y espacios específicos, distintos al aula, en los que se permita su uso para fines recreativos o de comunicación personal; </p>
                </li>
                <li>
                    <p class="texto_general">Promover el uso seguro y responsable de la tecnología, con especial énfasis en la prevención de riesgos asociados al ciberacoso, la violencia en sus diversos tipos y modalidades y el acceso a contenidos que vulneren el sano desarrollo de niñas, niños y adolescentes; y<br></p>
                </li>
                <li>
                    <p class="texto_general">Fomentar la participación corresponsable de madres, padres o personas que ejerzan la tutela en el acompañamiento del uso de teléfonos celulares y dispositivos electrónicos.<br></p>
                </li>
            </ul>
        </div>
    </div>
    <div class="div-section-text">
        <h3 class="h3_centrado">Como parte de estas reformas, también,  se adicionó a la Ley de los Derechos de Niñas, Niños y Adolescentes del Estado de México un segundo párrafo a la fracción I del artículo 28 para quedar de la siguiente manera:</h3>
        <div class="texto_section">
            <p class="texto_general">“Las tecnologías de la información, comunicación, conocimiento y aprendizaje digital serán utilizadas como un complemento de los demás materiales educativos, incluidos los libros de texto gratuitos. <br><br>El uso de dispositivos de telefonía celular y demás dispositivos electrónicos por parte de niñas, niños y adolescentes en las escuelas de nivel básico deberá sujetarse a fines estrictamente académicos, de conformidad con lo previsto en el artículo 61 Bis del presente ordenamiento. “</p>
        </div>
    </div>
