        <h3 class="h3_centrado">¿Qué dice la reforma a la Ley de Educación del Estado de México?</h3>
        <div class="texto_section">
            <p class="texto_general">Las, le y los diputados de la LXII Legislatura mexiquense aprobaron reformar el segundo párrafo del artículo 58 y adicionaron el artículo 61 BIS que describe los detalles de cómo el estudiantado podrá usar o no celulares y otros dispositivos electrónicos en instituciones educativas de nivel básico en la entidad mexiquense.</p>
        </div>
    </div>
    <div class="div-section-text">
        <h3 class="h3_centrado">El artículo 58 expresa:</h3>
        <div class="texto_section">
            <p class="texto_general">“Las tecnologías de la información, comunicación, conocimiento y aprendizaje digital serán utilizadas como un complemento de los demás materiales educativos, incluidos los libros de texto gratuitos. <br><br>El uso de dispositivos de telefonía celular y demás dispositivos electrónicos por parte de niñas, niños y adolescentes en las escuelas de nivel básico deberá sujetarse a fines estrictamente académicos, de conformidad con lo previsto en el artículo 61 Bis del presente ordenamiento. “</p>
        </div>
    </div>
    <div class="div-section-text">
        <h3 class="h3_centrado">En tanto, el artículo 61 Bis refiere que:</h3>
        <div class="texto_section">
            <div class="columns-2 w-row">
                <div class="w-col w-col-6">
                    <p class="texto_general">“El uso de dichos dispositivos quedará limitado exclusivamente a fines académicos previstos en los lineamientos generales del uso responsable y seguro de las tecnologías de la información, comunicación, conocimiento y aprendizaje digital en el sistema educativo o, en caso de emergencias personales, previa autorización expresa del personal docente o directivo.<br><br>En ningún caso podrá permitirse que interfieran con el desarrollo de las actividades escolares, la convivencia armónica de la comunidad educativa o el ejercicio de los derechos de niñas, niños y adolescentes.”</p>
                </div>
                <div class="w-col w-col-6">
