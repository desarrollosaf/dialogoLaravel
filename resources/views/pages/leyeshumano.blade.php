                <p class="texto">Además de crear la Comisión Legislativa de Seguimiento a los Casos de Amnistía de manera plural y con la categoría de permanente, que acordó la posibilidad de promover o solicitar el trámite para que una persona recupere su libertad y se reforzó la asesoría, orientación y defensa jurídica a las personas solicitantes por parte del Instituto de la Defensoría Pública y la Comisión de Derechos Humanos, ambas de la entidad.</p>
                <p class="texto">Adicionalmente, se aprobó la eliminación de la prisión vitalicia del Código Penal estatal, al considerar que esta figura implica la privación perpetua de la libertad sin posibilidad de revisión ni reducción de la pena, suprime toda expectativa de reinserción social y convierte la sanción en una medida estrictamente retributiva.</p>
