            <div class="columna columna--ancha">
                <p class="texto">Para garantizar el derecho a la salud desde un enfoque integral e interseccional, el Congreso mexiquense aprobó una nueva ley de salud fundamentada en principios como la gratuidad en el sector público, humanismo, interés superior de la niñez, perspectiva de género, progresividad, universalidad y justicia social.</p>
                <p class="texto">Este ordenamiento identifica como grupos de atención prioritaria a las personas adultas mayores; mujeres y personas gestantes; niñas, niños y adolescentes; personas con discapacidad; personas en situación de calle; integrantes de la comunidad LGBTTTIQ+ (lésbica, gay, bisexual, transgénero, travesti, transexual, intersexual, queer y más); personas migrantes; pueblos y comunidades indígenas y afromexicanas, así como víctimas de delitos o violaciones a derechos humanos.</p>
            </div>
        </div>
    </section>

    <!-- Deporte -->
    <section class="grupo grupo--deporte reveal">
        <div class="grupo__banda"><h2>Deporte</h2></div>
        <div class="grupo__cuerpo">
            <div class="fila fila--invertida fila--separada">
