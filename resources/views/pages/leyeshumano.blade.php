                <div class="columna">
                    <p class="texto">Desde la instalación de la Comisión para la Defensa de Derechos de las Poblaciones LGBTTTIQ+ (Lesbianas, Gays, Bisexuales, Transgénero, Travesti, Transexuales, Intersexual, Queer y más), el 23 de octubre de 2024, el Congreso mexiquense ha avanzado en el reconocimiento de los derechos de la comunidad de la diversidad sexogenérica en materia de identidad y una vida libre de violencia, además de visibilizar el activismo a favor de esta comunidad.</p>
                    <p class="texto">Durante el segundo año legislativo, la LXII Legislatura mexiquense tipificó el transfeminicidio como delito con sanciones de hasta 93 años y cuatro meses de prisión y avaló incluir la opción de identidad ‘no binaria’ en la expedición de acta por rectificación para el reconocimiento de identidad de género.</p>
