    <section class="grupo grupo--indigenas reveal">
        <div class="grupo__banda"><h2>Indígenas</h2></div>
        <div class="grupo__cuerpo fila fila--amplia">
            <div class="ilustracion"><img src="{{ asset("assets/leyesHumano/uploads/ilustraciones_blog/04-mujer-indigena.webp") }}" alt="Mujer indígena de cuerpo completo con rebozo gris y vestido rosa"></div>
            <div class="columna columna--ancha">
                <p class="texto">El Congreso local aprobó reformas constitucionales para reconocer a los pueblos y comunidades indígenas y afromexicanas como sujetos de derecho público con personalidad jurídica y patrimonio propio, así como su libre determinación en el marco de la unidad nacional, además de emitir un exhorto para ampliar el Catálogo Nacional de Pueblos y Comunidades Indígenas y Afromexicana, así como verificar el cumplimiento de la obligación de los municipios de contar con una dirección de asuntos indígenas, o equivalente.</p>
                <p class="texto">También exhortó al Instituto Nacional de los Pueblos Indígenas (INPI) a realizar las acciones necesarias para registrar a los pueblos de Calixtlahuaca, Tecaxic y Tlacotepec, pertenecientes a Toluca, en el Catálogo Nacional de Pueblos y Comunidades Indígenas y Afromexicanas, así como a las y los presidentes municipales de 48 de los 125 municipios (hasta febrero de 2025) a informar sobre el cumplimiento de la obligación de contar con una dirección de asuntos indígenas, o equivalente.</p>
                <p class="texto">El Pleno del Congreso mexiquense también exhortó a Claudia Regina Jiménez Valdez, encargada del despacho de la Vocalía Ejecutiva del Consejo Estatal para el Desarrollo Integral de los Pueblos Indígenas del Estado de México (Cedipiem), y a Adelfo Regino Montes, director general del INPI, a realizar las acciones necesarias con el propósito de homologar el Listado de Localidades Indígenas del Estado de México con el Catálogo Nacional de Localidades Indígenas.</p>
            </div>
        </div>
