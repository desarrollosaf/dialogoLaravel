                <div class="columna">
                    <p class="texto">El Congreso mexiquense incorporó a la Constitución local el derecho de toda persona a la cultura y activación física, así como a la práctica del deporte, además de establecer en la legislación secundaria el derecho de las juventudes a realizar actividades recreativas y a contar con espacios adecuados que favorezcan un uso positivo y productivo de su tiempo libre.</p>
                    <p class="texto">Asimismo, con el objetivo de fomentar la salud, la integración social, la paz y el desarrollo de valores cívicos a través de la actividad física y el deporte, la LXII Legislatura mexiquense aprobó declarar el día 6 de cada mes como Día del Deporte en el Estado de México y el 6 de abril de cada año como Día Estatal de las y los Deportistas Mexiquenses.</p>
                </div>
            </div>
            <p class="texto">Por otro lado, en virtud de que el deporte y el juego constituyen herramientas eficaces para la transformación social, al promover y consolidar los derechos humanos y una vida más saludable, se estableció que el Estado y los municipios fomenten, a través de las actividades físicas, recreativas y deportivas, actitudes solidarias, la cultura de paz, el respeto a la legalidad y la no violencia en todas sus manifestaciones.</p>
        </div>
    </section>

    <!-- Justicia -->
    <section class="grupo grupo--justicia reveal">
        <div class="grupo__banda"><h2>Justicia con enfoque social</h2></div>
        <div class="grupo__cuerpo fila">
