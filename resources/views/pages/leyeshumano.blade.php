                <p class="texto columna">La niñez y adolescencia es otro de los grupos prioritarios en la agenda del Congreso mexiquense, por lo que se ha actualizado el marco jurídico para prevenir el abuso sexual, mediante sanciones de hasta 16 años de prisión para quien use tecnologías de la información y la comunicación con este fin o para solicitar material audiovisual con contenido explícito, además de establecer un protocolo por parte de los prestadores de servicios para detectar y prevenir delitos de explotación sexual infantil en servicios de hospedaje o alojamiento.</p>
            </div>
            <p class="texto">También, para evitar la impunidad, se aprobó que la acción para exigir la reparación del daño derivado de actos de violencia sexual cometidos en contra de menores sea imprescriptible y se establecieron penas de hasta 15 años de prisión para quien obligue, procure, induzca, coaccione, solicite, gestione, oferte, ofrezca, consienta o facilite a una persona menor de edad establecer matrimonio, concubinato o cohabitación forzada.</p>
            <p class="texto texto--mas-espacio">Además de favorecer la conciliación entre la vida laboral, familiar y personal, la LXII Legislatura también acordó la protección de este sector en casos de emergencias o desastres, reconocer su derecho a una alimentación nutritiva, suficiente y de calidad y favorecer la incorporación de jóvenes recién egresados al sector productivo mediante una bolsa de trabajo con mecanismos específicos para este grupo.</p>
