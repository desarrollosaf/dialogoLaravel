    <section class="grupo grupo--mujeres reveal">
        <div class="grupo__banda"><h2>Mujeres</h2></div>
        <div class="grupo__portada">
            <img data-reveal-img src="{{ asset("assets/leyesHumano/uploads/ilustraciones_blog/01-mujeres.webp") }}" alt="Cuatro mujeres de pie, con flores rosas flotando a su alrededor">
        </div>
        <div class="grupo__cuerpo">
            <p class="texto">Para prevenir, combatir y erradicar las conductas que impiden una igualdad sustantiva y vulneran derechos fundamentales de las mujeres, la LXII Legislatura mexiquense ha fortalecido la respuesta judicial ante la violencia de género mediante la creación del Juzgado LIBRE (Libertad, Igualdad, Bienestar, Redes y Emancipación), además de definir y penalizar, así como aumentar los supuestos y sanciones por modalidades de violencia de carácter sexual, digital y familiar.</p>
            <p class="texto">El Congreso mexiquense aprobó la inclusión de las niñas, adolescentes y mujeres que se encuentran en situación de ofendidos o víctimas de violencia en los programas sociales; incorporó la corresponsabilidad familiar en la convivencia matrimonial o de concubinato y reconoció el trabajo doméstico y de cuidados como aportaciones reclamables en juicios por alimentos, guarda y custodia, compensaciones y liquidación de regímenes patrimoniales.</p>
            <p class="texto">Además de retirar las exenciones de responsabilidad a quienes encubran a personas investigadas o vinculadas a proceso por feminicidio, se protegió, a través de programas, acciones y servicios de asistencia social, a niñas, niños y adolescentes que estén en condición de orfandad por este delito o sean dependientes de víctimas por desaparición.</p>
        </div>
    </section>

    <!-- Niñez y juventudes -->
    <section class="grupo grupo--ninez reveal">
