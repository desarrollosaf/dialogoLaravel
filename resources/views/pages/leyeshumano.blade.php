            <p class="texto columna">Para garantizar los derechos de las 2.3 millones de personas adultas mayores en la entidad, el Congreso mexiquense avaló que este sector poblacional reciba atención preferente, digna y expedita en todos los trámites, servicios y procedimientos que presten las dependencias y entidades de la administración pública estatal, los ayuntamientos y sus organismos auxiliares.</p>
