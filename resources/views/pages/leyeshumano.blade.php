                <p class="texto columna">En materia educativa, resalta la regulación del uso de teléfonos celulares en la educación básica, así como la promoción, en el nivel medio superior y superior, del uso responsable, ético y gradual de la Inteligencia Artificial (IA), así como la expedición de la Ley de Fomento para la Lectura y el Libro del Estado de México para promover esta actividad, especialmente en zonas rurales y en poblaciones en situación de vulnerabilidad; generar publicaciones accesibles; contribuir a erradicar el analfabetismo; así como apoyar a personas escritoras y la edición de sus obras.</p>
            </div>
        </div>
    </section>

